import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { convertRecords } from '../src/index.js';
import type { RawRecord } from '../src/index.js';

/**
 * The webcam eye tracker's output, read by the package that consumes it (#430).
 *
 * `tools/eyetrack/calibrate/` records gaze over screenshots and writes one JSON file whose
 * `records` are this package's `RawRecord`s. That is a promise between a tool nothing here
 * imports and a converter nothing there imports, so it is asserted from this side, against a
 * committed file the tool itself wrote.
 *
 * Four claims, and the reason each is here rather than in the tool's README:
 *
 * 1. **The file converts.** `convertRecords` takes `.records` and returns sessions the
 *    contract's own schema accepts, with `kind: "real"` and a participant. If a field of the
 *    raw shape is renamed on this side, this fails instead of a participant's afternoon.
 * 2. **The fixations are derived, not written.** The tool's own `fixations.js` is loaded and
 *    re-run over the raw gaze committed beside them in the same file. Fixations are an
 *    interpretation of gaze; this pins the interpretation to the code that made it, so the
 *    sample cannot drift into a hand-written list that merely happens to validate.
 * 3. **Nothing is uploaded.** The tool's own sources are scanned for every networking entry
 *    point a browser offers. The claim on its page is that the code has none, and a claim
 *    about bytes is checkable.
 * 4. **The vendored library is the one that was vendored.** Pinned by digest, because "no
 *    network at run time" is a property of a particular 2.2 MB file and of no other.
 *
 * **The sample's gaze is synthetic**, which it says in its own `gazeSource`, and which this
 * file asserts: nobody may mistake it for a recording of a person. It stands in exactly as
 * `test/corpus` stands in for UEyes — generated by committed code, in the real shape.
 */

/** The repository root, three directories above `packages/calibration/test`. */
const ROOT = fileURLToPath(new URL('../../../', import.meta.url));

const TOOL_DIR = join(ROOT, 'tools/eyetrack/calibrate');

const SAMPLE_PATH = join(TOOL_DIR, 'sample/p01-three-screenshots.json');

/**
 * WebGazer.js 1.0.1 as this repository vendors it: the `index.js` of the npm package
 * `webgazer@1.0.1`, unchanged.
 *
 * The digest is the point of the version choice. Every later WebGazer loads a TensorFlow.js
 * face-landmark model over the network the first time it runs, which the tool may not do;
 * 1.0.1 carries its face tracker inside itself. A swap for a newer one would keep the page
 * working and quietly break the promise, so the file is pinned rather than the version
 * string. `tools/eyetrack/calibrate/vendor/README.md` records where it came from.
 */
const VENDOR_SHA256 = '93c51216925877b0019f7776dce7d84c903ec224fbd80b6d386380eff67cef5f';

/**
 * Every way a browser can reach a host, as an identifier.
 *
 * The test is that the tool's sources do not so much as *name* one — a stricter rule than
 * "does not call one", chosen because it needs no parser to be true and no judgement to
 * check. It is why those files' comments talk about networking without spelling it.
 */
const NETWORK_IDENTIFIERS = [
  'fetch',
  'XMLHttpRequest',
  'WebSocket',
  'EventSource',
  'sendBeacon',
  'importScripts',
  'serviceWorker',
  'RTCPeerConnection',
  'navigator.connection',
] as const;

/** The tool's own files: the ones this ticket wrote, as opposed to the vendored library. */
const TOOL_SOURCES = ['index.html', 'eyetrack.js', 'fixations.js'] as const;

/** One gaze estimate as the tool records it, in image space. */
interface GazeSample {
  readonly tMs: number;
  readonly x: number;
  readonly y: number;
}

/** A record as the tool writes it: this package's `RawRecord`, plus the gaze behind it. */
interface RecordedRecord extends RawRecord {
  readonly gaze: readonly GazeSample[];
  readonly dropped: { readonly outsideImage: number; readonly outOfOrder: number };
}

/** The one file a participant saves. */
interface RecordedFile {
  readonly tool: string;
  readonly writerVersion: number;
  readonly format: string;
  readonly gazeSource: string;
  readonly participantId: string;
  readonly tracker: { readonly name: string; readonly version: string };
  readonly calibration: {
    readonly points: number;
    readonly clicksPerPoint: number;
    readonly check: { readonly samples: number; readonly meanErrorPx: number | null };
  };
  readonly fixationDetector: {
    readonly dispersionPx: number;
    readonly minDurationMs: number;
    readonly maxGapMs: number;
  };
  readonly records: readonly RecordedRecord[];
}

/** What `fixations.js` exposes, narrowed to what this file uses. */
interface EyetrackCore {
  readonly DISPERSION_PX: number;
  readonly MIN_DURATION_MS: number;
  readonly MAX_GAP_MS: number;
  readonly detectFixations: (
    gaze: readonly GazeSample[],
  ) => readonly { tMs: number; durationMs: number; x: number; y: number }[];
}

/**
 * Load the tool's arithmetic.
 *
 * `fixations.js` is a classic browser script, not a module: the page has to run from a
 * `file://` URL, where a browser refuses an ES module. So it is given a host object to hang
 * its namespace on, exactly as a browser gives it `window` — which also means this runs the
 * committed bytes and leaves nothing behind in this process's globals.
 */
const loadCore = (): EyetrackCore => {
  const source = readFileSync(join(TOOL_DIR, 'fixations.js'), 'utf8');
  const host: { eyetrackFixations?: EyetrackCore } = {};

  new Function('globalThis', source)(host);
  const core = host.eyetrackFixations;
  if (core === undefined) throw new Error('fixations.js did not define eyetrackFixations');
  return core;
};

const sample = JSON.parse(readFileSync(SAMPLE_PATH, 'utf8')) as RecordedFile;

describe('the eye tracker’s file is this package’s raw-record shape', () => {
  it('names which shape it is, and the writer that produced it', () => {
    expect(sample.tool).toBe('personavision/tools/eyetrack/calibrate');
    expect(sample.format).toBe('packages/calibration RawRecord[] under .records');
    expect(sample.writerVersion).toBeGreaterThanOrEqual(1);
  });

  it('converts whole, with nothing rejected', () => {
    const { sessions, rejections } = convertRecords(sample.records);

    expect(rejections).toEqual([]);
    expect(sessions).toHaveLength(sample.records.length);
  });

  it('becomes real sessions carrying a participant and no persona', () => {
    const { sessions } = convertRecords(sample.records);

    for (const converted of sessions) {
      expect(converted.session.kind).toBe('real');
      expect(converted.session.participant).toEqual({ id: sample.participantId });
      // A participant is a human being, not a generated person, and nothing was sampled.
      expect(converted.session.persona).toBeNull();
      expect(converted.session.seed).toBeNull();
    }
  });

  it('carries the display the participant actually saw, not the image’s own size', () => {
    const { sessions } = convertRecords(sample.records);

    for (const converted of sessions) {
      const record = sample.records.find((candidate) => candidate.id === converted.recordId);
      // Thrown rather than asserted: `image` and `display` are nullable on the raw shape, so
      // a soft assertion here would leave the three claims below comparing against a
      // fallback — green, and checking nothing.
      if (record === undefined) throw new Error(`no record for ${converted.recordId}`);
      const { image, display } = record;
      if (image === null || display === null) {
        throw new Error(`record ${record.id} has no image or no display`);
      }

      // A screenshot is shown shrunk to fit the display, so the scale is above one and the
      // viewport is narrower than the image. A record that recorded the image's size instead
      // would score a prediction at a resolution nobody was shown.
      expect(converted.display.scale).toBeGreaterThan(1);
      expect(converted.display.viewport.width).toBeLessThan(image.width);
      expect(converted.display.viewport.width).toBe(display.viewportWidth);
    }
  });

  it('puts every fixation on the screenshot and in order', () => {
    const { sessions } = convertRecords(sample.records);

    for (const converted of sessions) {
      const { fixations } = converted.session;
      expect(fixations.length).toBeGreaterThan(0);
      let previousEnd = -1;
      let previousOnset = -1;
      for (const fixation of fixations) {
        expect(fixation.x).toBeGreaterThanOrEqual(0);
        expect(fixation.y).toBeGreaterThanOrEqual(0);
        expect(fixation.x).toBeLessThanOrEqual(converted.imageSize.width);
        expect(fixation.y).toBeLessThanOrEqual(converted.imageSize.height);
        expect(fixation.tMs).toBeGreaterThan(previousOnset);
        expect(fixation.tMs).toBeGreaterThanOrEqual(previousEnd);
        expect(fixation.tMs).toBeLessThanOrEqual(converted.viewingDurationSeconds * 1000);
        previousOnset = fixation.tMs;
        previousEnd = fixation.tMs + fixation.durationMs;
      }
    }
  });

  it('says plainly that its gaze is synthetic', () => {
    // The committed sample is a stand-in, as `test/corpus` is for UEyes. A file that did not
    // say so could be read as an afternoon of somebody's attention.
    expect(sample.gazeSource).toBe('synthetic');
  });

  it('records the calibration that was measured before recording was allowed', () => {
    expect(sample.calibration.points).toBe(9);
    expect(sample.calibration.clicksPerPoint).toBeGreaterThan(0);
    expect(sample.calibration.check.samples).toBeGreaterThan(0);
    expect(sample.calibration.check.meanErrorPx).toBeGreaterThan(0);
    expect(sample.tracker.name).toBe('WebGazer.js');
  });
});

describe('the sample’s fixations are the tool’s own reading of its raw gaze', () => {
  const core = loadCore();

  it('re-derives every fixation from the gaze committed beside it', () => {
    expect(sample.records.length).toBeGreaterThan(0);

    for (const record of sample.records) {
      const committed = record.participants[0].fixations.map((fixation) => ({
        tMs: fixation.tMs,
        durationMs: fixation.durationMs,
        x: fixation.x,
        y: fixation.y,
      }));

      expect(core.detectFixations(record.gaze), record.id).toEqual(committed);
    }
  });

  it('read the gaze with the thresholds the file reports', () => {
    expect(sample.fixationDetector.dispersionPx).toBe(core.DISPERSION_PX);
    expect(sample.fixationDetector.minDurationMs).toBe(core.MIN_DURATION_MS);
    expect(sample.fixationDetector.maxGapMs).toBe(core.MAX_GAP_MS);
  });

  it('kept the raw gaze, which is the measurement the fixations interpret', () => {
    for (const record of sample.records) {
      expect(record.gaze.length, record.id).toBeGreaterThan(
        record.participants[0].fixations.length,
      );
      // Gaze that left the screenshot is dropped rather than clamped, and counted rather
      // than hidden: the share that missed is how a reader judges a recording.
      expect(record.dropped.outsideImage, record.id).toBeGreaterThanOrEqual(0);
    }
  });
});

describe('the tool uploads nothing', () => {
  it.each(TOOL_SOURCES)('%s names no way of reaching a host', (name) => {
    const text = readFileSync(join(TOOL_DIR, name), 'utf8');

    expect(text.length).toBeGreaterThan(0);
    for (const identifier of NETWORK_IDENTIFIERS) {
      expect(text, `${name} names ${identifier}`).not.toContain(identifier);
    }
  });

  it('and the page loads nothing from another origin', () => {
    const html = readFileSync(join(TOOL_DIR, 'index.html'), 'utf8');

    for (const pattern of ['src="http', "src='http", 'src="//', 'href="http', 'href="//']) {
      expect(html, pattern).not.toContain(pattern);
    }
  });

  it('and says so on the page, where the participant reads it', () => {
    const html = readFileSync(join(TOOL_DIR, 'index.html'), 'utf8');

    expect(html).toContain('Nothing is uploaded.');
    expect(html).toContain('makes no network request');
  });
});

describe('the vendored library is the file that was vendored', () => {
  const vendored = readFileSync(join(TOOL_DIR, 'vendor/webgazer.js'));

  it('byte for byte', () => {
    expect(createHash('sha256').update(vendored).digest('hex')).toBe(VENDOR_SHA256);
  });

  it('and that file asks for nothing over the network while it runs', () => {
    const text = vendored.toString('utf8');

    // It bundles `numeric.js`, whose `getURL` helper wraps the browser's request object.
    // WebGazer never calls it — gaze is estimated from the camera frame and nothing is
    // loaded — so the one occurrence is pinned here: a second would be a real request.
    expect(text.split('XMLHttpRequest')).toHaveLength(2);
    expect(text).toContain('numeric.getURL');
    expect(text).not.toContain('fetch(');
  });

  it('and comes with its licence', () => {
    const licence = readFileSync(join(TOOL_DIR, 'vendor/LICENSE'), 'utf8');

    expect(licence).toContain('GNU General Public License');
    expect(licence).toContain('Brown HCI Group');
  });
});
