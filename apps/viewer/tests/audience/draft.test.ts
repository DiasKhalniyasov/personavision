import { describe, expect, it } from 'vitest';
import { runSchema } from '@personavision/contract';
import { readRunFile } from '../app';
import {
  audienceOf,
  chosenPercentTotal,
  draftOf,
  emptyDraft,
  GENERATOR_VERSION,
  seedForDay,
  slugOf,
  withChip,
} from '../../src/screens/audience/draft';
import type { AudienceDraft } from '../../src/screens/audience/draft';

/**
 * The form's two directions: an audience filled into it, and the audience it describes.
 *
 * What is asserted here is the behaviour a reader can see on the screen — that the age
 * range and the device mix are refused at the field they are wrong at rather than quietly
 * repaired, and that an audience round-trips through the form unchanged.
 */

const SEED_RUN_ID = '2026-10-24-1402-northwind-demo';
const seedAudience = () => runSchema.parse(readRunFile(SEED_RUN_ID)).audience;

const withDevices = (draft: AudienceDraft, percents: Record<string, string>): AudienceDraft => ({
  ...draft,
  devices: draft.devices.map((device) => ({
    ...device,
    chosen: percents[device.name] !== undefined,
    percent: percents[device.name] ?? device.percent,
  })),
});

const filled = (): AudienceDraft => draftOf(seedAudience());

describe('the generator a new audience is described for', () => {
  it('is the one the committed example run was generated by', () => {
    expect(seedAudience().generatedFrom.generatorVersion).toBe(GENERATOR_VERSION);
  });
});

describe('an audience filled into the form', () => {
  it('comes back out of it unchanged', () => {
    const audience = seedAudience();
    const result = audienceOf(draftOf(audience));

    expect(result.ok && result.audience).toEqual(audience);
  });

  it('keeps the id it was stored under when it is renamed, so a finished test still names it', () => {
    const renamed = { ...filled(), name: 'Weekend hikers' };
    const result = audienceOf(renamed);

    expect(result.ok && result.audience.id).toBe('outdoor-gear-shoppers');
    expect(result.ok && result.audience.name).toBe('Weekend hikers');
  });

  it('offers every device class, and presses only the ones the audience declares', () => {
    const devices = filled().devices;

    expect(devices.map((device) => [device.label, device.chosen, device.percent])).toEqual([
      ['Mobile', true, '60'],
      ['Desktop', true, '40'],
      ['Tablet', false, '0'],
    ]);
  });
});

describe('a new audience', () => {
  it('starts empty, and is named for the day it was described', () => {
    const draft = emptyDraft(new Date(2026, 9, 27));

    expect(draft.name).toBe('');
    expect(draft.ageMin).toBe('');
    expect(draft.roles.chosen).toEqual([]);
    expect(draft.seed).toBe(20_261_027);
    expect(seedForDay(new Date(2026, 0, 2))).toBe(20_260_102);
  });

  it('takes its id from its name', () => {
    const draft = {
      ...emptyDraft(new Date(2026, 9, 27)),
      name: 'Trade & wholesale buyers',
      ageMin: '30',
      ageMax: '60',
    };
    const result = audienceOf(draft);

    expect(result.ok && result.audience.id).toBe('trade-wholesale-buyers');
    expect(slugOf('  Outdoor-gear shoppers ')).toBe('outdoor-gear-shoppers');
  });

  it('is refused without a name, at the name field', () => {
    const draft = { ...emptyDraft(new Date(2026, 9, 27)), ageMin: '25', ageMax: '45' };
    const result = audienceOf(draft);

    expect(result.ok).toBe(false);
    expect(!result.ok && result.issues.map((issue) => issue.path)).toEqual(['name']);
  });

  it('is refused without an age range, at each end that is missing', () => {
    const draft = { ...emptyDraft(new Date(2026, 9, 27)), name: 'Hikers' };
    const result = audienceOf(draft);

    expect(!result.ok && result.issues.map((issue) => issue.path)).toEqual([
      'ageRange.min',
      'ageRange.max',
    ]);
  });
});

describe('the age range', () => {
  it('is refused when it runs backwards, and says which way round it is', () => {
    const result = audienceOf({ ...filled(), ageMin: '60', ageMax: '30' });

    expect(!result.ok && result.issues).toEqual([
      { path: 'ageRange', message: 'an age range runs from min to max: found 60–30' },
    ]);
  });
});

describe('the device mix', () => {
  it('is refused when the shares do not add up, and says what they add up to', () => {
    const result = audienceOf(withDevices(filled(), { mobile: '60', desktop: '35' }));

    expect(!result.ok && result.issues).toEqual([
      {
        path: 'devices',
        message:
          'the device shares are a mix of one audience: they must add up to 100%, and these add up to 95%',
      },
    ]);
  });

  it('is never normalised: what was typed is what is still there', () => {
    const typed = withDevices(filled(), { mobile: '60', desktop: '35' });

    expect(chosenPercentTotal(typed)).toBe(95);
    expect(typed.devices.map((device) => device.percent)).toEqual(['60', '35', '0']);
  });

  it('is refused when no device is chosen at all', () => {
    const result = audienceOf(withDevices(filled(), {}));

    expect(!result.ok && result.issues.map((issue) => issue.path)).toEqual(['devices']);
  });

  it('turns whole percentage points into the shares the contract takes', () => {
    const result = audienceOf(withDevices(filled(), { mobile: '25', tablet: '75' }));

    expect(
      result.ok && result.audience.devices.map((device) => [device.name, device.share]),
    ).toEqual([
      ['mobile', 0.25],
      ['tablet', 0.75],
    ]);
  });
});

describe('a chip group', () => {
  it('adds a value the suggestions do not hold, and presses it', () => {
    const draft = emptyDraft(new Date(2026, 9, 27));
    const roles = withChip(draft.roles, 'Wholesaler', true);

    expect(roles.offered.at(-1)).toBe('Wholesaler');
    expect(roles.chosen).toEqual(['Wholesaler']);
  });

  it('releases a value without taking it off the row', () => {
    const draft = emptyDraft(new Date(2026, 9, 27));
    const pressed = withChip(draft.roles, 'Gift buyer', true);
    const released = withChip(pressed, 'Gift buyer', false);

    expect(released.chosen).toEqual([]);
    expect(released.offered).toContain('Gift buyer');
  });
});
